type Dict = typeof dict;
// 'a.b.c' 경로 타입
type Paths<T> = {
  [K in keyof T & string]: T[K] extends string ? K : T[K] extends object ? `${K}.${Paths<T[K]>}` : never;
}[keyof T & string];
export type LabelKey = Paths<Dict>;

/** 사전에서 글자를 꺼낸다. 없는 키는 개발 중 바로 보이게 키 그대로. {n} 자리는 vars로 채운다 */
export function t(key: LabelKey | (string & {}), vars?: Record<string, string | number>): string {
  let v: unknown = dict;
  for (const k of key.split('.')) v = v && typeof v === 'object' ? (v as Record<string, unknown>)[k] : undefined;
  if (typeof v !== 'string') return key;
  return vars ? v.replace(/\{(\w+)\}/g, (m, k: string) => String(vars[k] ?? m)) : v;
}
